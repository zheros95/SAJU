// ───── 본문 용어 자동 풀이 부착 ─────
let _re = null;
function buildRe() {
  const terms = Object.keys(GLOSSARY)
    .filter(t => t.length >= 2) // 한 글자 용어(병·사·묘 등)는 오인식 위험으로 제외
    .sort((a, b) => b.length - a.length) // 긴 용어 우선(정재격 > 정재)
    .map(t => t.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
  _re = terms.length ? new RegExp(terms.join('|'), 'g') : null;
}

// 풀이를 붙일 본문 영역만 (표·타임라인·배지 등 좁은 칸은 제외)
const TARGETS = '.prose p, .luck-lines li, .sinsal-chip p, .pr-block p, .rel-chip p, .today-text p, .cp-sec-body, .cp-sec-rel, .pr-life, .mini-note';

export function annotate(root) {
  if (!root) return;
  if (_re === null) buildRe();
  if (!_re) return;
  root.querySelectorAll(TARGETS).forEach(el => {
    const scope = el.closest('.card, .today-card') || root;
    if (!scope.__easySeen) scope.__easySeen = new Set();
    const seen = scope.__easySeen;
    const walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT, {
      acceptNode(n) {
        if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        if (n.parentElement && n.parentElement.closest('.easy')) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      },
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => {
      const text = node.nodeValue;
      _re.lastIndex = 0;
      if (!_re.test(text)) return;
      _re.lastIndex = 0;
      const frag = document.createDocumentFragment();
      let last = 0, m;
      while ((m = _re.exec(text))) {
        const term = m[0];
        frag.appendChild(document.createTextNode(text.slice(last, m.index) + term));
        last = m.index + term.length;
        if (!seen.has(term)) { // 카드당 같은 용어는 1번만 풀이
          seen.add(term);
          const s = document.createElement('span');
          s.className = 'easy';
          s.textContent = `(${GLOSSARY[term]})`;
          frag.appendChild(s);
        }
      }
      frag.appendChild(document.createTextNode(text.slice(last)));
      node.parentNode.replaceChild(frag, node);
    });
  });
}

